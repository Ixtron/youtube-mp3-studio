"""
Вспомогательный скрипт для авторизации YouTube через встроенный браузер.
Запускается как отдельный процесс из основного приложения.

Открывает окно WebView2, пользователь входит в YouTube,
куки автоматически сохраняются в файл и процесс завершается.
"""
import sys
import os
import time
import threading
from http.cookies import SimpleCookie
from urllib.parse import urlparse

import webview

if sys.stdout:
    sys.stdout.reconfigure(encoding='utf-8')
if sys.stderr:
    sys.stderr.reconfigure(encoding='utf-8')


def save_cookies_netscape(cookies_list, filepath):
    """Сохранить куки из pywebview в файл Netscape cookies.txt."""
    lines = [
        "# Netscape HTTP Cookie File",
        "# https://curl.haxx.se/docs/http-cookies.html",
        "# This file was generated by YouTube to MP3 Downloader",
        ""
    ]
    cookie_count = 0
    now_ts = int(time.time())
    one_year_later = str(now_ts + 365 * 24 * 3600)

    for cookie_obj in cookies_list:
        if isinstance(cookie_obj, SimpleCookie):
            for name, morsel in cookie_obj.items():
                domain = morsel.get('domain', '') or '.youtube.com'
                path = morsel.get('path', '') or '/'
                secure = 'TRUE' if morsel.get('secure', '') else 'FALSE'

                expires = morsel.get('expires', '')
                if expires:
                    try:
                        from email.utils import parsedate_to_datetime
                        dt = parsedate_to_datetime(expires)
                        expires_ts = str(int(dt.timestamp()))
                    except Exception:
                        expires_ts = one_year_later
                else:
                    expires_ts = one_year_later

                subdomain = 'TRUE' if domain.startswith('.') else 'FALSE'
                value = morsel.value

                line = f"{domain}\t{subdomain}\t{path}\t{secure}\t{expires_ts}\t{name}\t{value}"
                lines.append(line)
                cookie_count += 1
        else:
            try:
                domain = getattr(cookie_obj, 'domain', '') or '.youtube.com'
                path = getattr(cookie_obj, 'path', '') or '/'
                secure = 'TRUE' if getattr(cookie_obj, 'secure', False) else 'FALSE'
                expires = getattr(cookie_obj, 'expires', None)
                if expires:
                    expires_ts = str(int(expires))
                else:
                    expires_ts = one_year_later
                subdomain = 'TRUE' if domain.startswith('.') else 'FALSE'
                name = getattr(cookie_obj, 'name', '')
                value = getattr(cookie_obj, 'value', '')

                if name:
                    line = f"{domain}\t{subdomain}\t{path}\t{secure}\t{expires_ts}\t{name}\t{value}"
                    lines.append(line)
                    cookie_count += 1
            except Exception:
                continue

    lines.append("")
    temporary = filepath + '.tmp'
    with open(temporary, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    os.replace(temporary, filepath)

    return cookie_count


def main():
    if len(sys.argv) < 2:
        print("ERROR:Не указан путь для сохранения куки", file=sys.stderr)
        sys.exit(1)

    cookies_path = sys.argv[1]

    login_url = (
        "https://accounts.google.com/ServiceLogin"
        "?service=youtube&uilel=3&passive=true"
        "&continue=https%3A%2F%2Fwww.youtube.com%2F"
    )

    window = webview.create_window(
        '🔑 Войдите в YouTube аккаунт',
        login_url,
        width=900,
        height=700,
        resizable=True,
    )

    def monitor_login():
        """Следим за URL — когда пользователь попадёт на youtube.com, забираем куки."""
        while True:
            try:
                time.sleep(2)
                current_url = window.get_current_url()
                if not current_url:
                    continue

                # Пользователь успешно вошёл и попал на YouTube
                host = urlparse(current_url).hostname or ''
                if ((host == 'youtube.com' or host.endswith('.youtube.com'))
                        and 'accounts.google' not in current_url
                        and 'signin' not in current_url
                        and 'ServiceLogin' not in current_url):
                    # Даём время для установки всех куки
                    time.sleep(3)

                    cookies = window.get_cookies()
                    names = set()
                    for cookie in cookies or []:
                        if isinstance(cookie, SimpleCookie):
                            names.update(cookie.keys())
                        else:
                            names.add(getattr(cookie, 'name', ''))
                    if not names.intersection({'SID', 'SAPISID', '__Secure-3PAPISID', '__Secure-1PAPISID'}):
                        continue
                    if cookies:
                        count = save_cookies_netscape(cookies, cookies_path)
                        # Сигнализируем основному приложению
                        print(f"OK:{count}")
                        sys.stdout.flush()
                    else:
                        print("ERROR:Куки пустые")
                        sys.stdout.flush()

                    # Закрываем окно
                    window.destroy()
                    return

            except Exception as e:
                # Окно уже закрыто или другая ошибка
                error_str = str(e)
                if 'destroy' not in error_str.lower():
                    print(f"ERROR:{error_str}")
                    sys.stdout.flush()
                return

    def on_started():
        monitor_thread = threading.Thread(target=monitor_login, daemon=True)
        monitor_thread.start()

    def on_closed():
        """Если пользователь закрыл окно вручную до входа."""
        pass

    window.events.closed += on_closed

    webview.start(on_started, gui='edgechromium')


if __name__ == '__main__':
    main()
